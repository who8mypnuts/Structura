"""Template export extras (docs/15 §5.2): user templates, the output preview, the autosaved script."""

from __future__ import annotations

from datetime import datetime
from pathlib import Path

import pytest

from structura.core.build.api import build_scene
from structura.core.lang.api import compile_script
from structura.core.scene.camera import Camera
from structura.export.api import EXPORTERS, export_scene, template_preview
from structura.export.templates import template_file
from structura.export.templates.autosave import autosave_path, script_with_settings
from structura.export.templates.template_file import all_templates, bundled_templates, save_user_template


def _scene(text: str = "20 * { x 1 } box\nsphere\n"):  # type: ignore[no-untyped-def]
    program = compile_script(text).program
    assert program is not None
    return build_scene(program, 1).scene


def test_the_preview_is_the_start_of_the_export(tmp_path: Path) -> None:
    scene, options = _scene(), {"template": "povray"}
    export_scene(scene, tmp_path / "a.pov", "template", options)
    full = (tmp_path / "a.pov").read_text(encoding="utf-8")
    assert template_preview(scene, options) == full[: 64 * 1024]
    assert template_preview(scene, options, limit=100) == full[:100]


def test_user_templates_are_listed_and_shadow_bundled_ones(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(template_file, "user_template_dir", lambda: tmp_path)
    xml = bundled_templates()["povray"].read_text(encoding="utf-8").replace("#declare", "// mine\n#declare", 1)
    path = save_user_template("My POV", xml)
    assert path.parent == tmp_path and all_templates()["My POV"] == path
    exporter = EXPORTERS["template"]
    exporter.refresh()  # type: ignore[attr-defined]
    assert "My POV" in exporter.params[0].choices
    assert "// mine" in template_preview(_scene(), {"template": "My POV"})
    with pytest.raises(ValueError):
        save_user_template("broken", "<template><primitive")
    monkeypatch.undo()
    exporter.refresh()  # type: ignore[attr-defined]


def test_the_autosaved_script_has_the_camera_and_seed() -> None:
    text = "set seed 3\nset maxdepth 50\nbox\n"
    camera = Camera(eye=(0.0, 0.0, 10.0), target=(0.0, 0.0, 0.0))
    out = script_with_settings(text, camera, 42, Path("/x/a.pov"), False, datetime(2024, 5, 1, 12, 0))
    assert out.count("set seed") == 1 and "set seed 42" in out and "set translation" in out
    assert "// Autogenerated script for file: /x/a.pov" in out and "set maxdepth 50" in out
    assert autosave_path(Path("/x/a.pov")) == Path("/x/a.es")
    program = compile_script(out).program
    assert program is not None
