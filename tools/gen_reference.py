"""Regenerate the language reference and the diagnostics table from the catalogues.

python tools/gen_reference.py          # write docs/reference/language.md and the table in docs/05 §10
python tools/gen_reference.py --check  # exit 1 if either file is stale (used by the tests)
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from structura.core.lang.catalog import diagnostic_specs
from structura.core.lang.reference import to_markdown

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / "docs" / "reference" / "language.md"
LANGUAGE_DOC = ROOT / "docs" / "05-eisenscript-language.md"
BEGIN, END = "<!-- diagnostics:begin (generated by tools/gen_reference.py) -->", "<!-- diagnostics:end -->"


def diagnostics_table() -> str:
    rows = ["| Code | Severity | Meaning |", "|------|----------|---------|"]
    rows += [f"| {d.code} | {d.severity} | {d.title} |" for d in diagnostic_specs().values()]
    return "\n".join([BEGIN, *rows, END])


def updated_language_doc(text: str) -> str:
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if pattern.search(text):
        return pattern.sub(lambda _m: diagnostics_table(), text)
    # first run: replace the hand-written table that follows the section heading
    section = re.compile(r"(## 10\. Diagnostics catalogue\n\n.*?\n\n)(\| Code \|.*?)(\n\n---)", re.S)
    return section.sub(lambda m: m.group(1) + diagnostics_table() + m.group(3), text, count=1)


def outputs() -> dict[Path, str]:
    return {REFERENCE: to_markdown() + "\n", LANGUAGE_DOC: updated_language_doc(LANGUAGE_DOC.read_text())}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    stale = [path for path, text in outputs().items() if not path.exists() or path.read_text() != text]
    if parser.parse_args().check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run python tools/gen_reference.py)")
        return 1 if stale else 0
    for path, text in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"wrote {len(outputs())} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
