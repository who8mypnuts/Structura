"""Write the built-in theme TOML files from tools/themes/palettes.toml (docs/13 §6).

PYTHONPATH=src:. python -m tools.themes.make_builtin
"""

from __future__ import annotations

import tomllib
from pathlib import Path
from typing import Any

import tomli_w

SOURCE = Path(__file__).resolve().parent / "palettes.toml"
OUT = Path(__file__).resolve().parents[2] / "src" / "structura" / "themes" / "builtin"
ROLES = {
    "ui.bg": "bg",
    "ui.bg.alt": "bg_alt",
    "ui.fg": "fg",
    "ui.accent": "accent",
    "editor.bg": "bg",
    "status.error": "error",
    "status.warning": "warning",
    "status.success": "success",
}
SYNTAX: dict[str, tuple[str, dict[str, bool]]] = {
    "syntax.keyword": ("keyword", {"bold": True}),
    "syntax.operator": ("operator", {}),
    "syntax.modifier": ("modifier", {"italic": True}),
    "syntax.number": ("number", {}),
    "syntax.color": ("color", {}),
    "syntax.primitive": ("primitive", {"bold": True}),
    "syntax.rule.def": ("rule", {"bold": True}),
    "syntax.rule.ref": ("rule", {}),
    "syntax.rule.undefined": ("error", {"underline": True}),
    "syntax.tag": ("tag", {}),
    "syntax.comment": ("comment", {"italic": True}),
    "syntax.preprocessor": ("preproc", {}),
    "syntax.define": ("preproc", {"italic": True}),
    "syntax.string": ("string", {}),
    "syntax.set.key": ("keyword", {}),
    "syntax.set.value": ("number", {}),
    "syntax.material": ("tag", {"italic": True}),
    "syntax.param": ("preproc", {}),
    "syntax.block": ("keyword", {"bold": True}),
}
META_KEYS = ("name", "kind", "family", "author", "license", "pair")


def theme_document(theme_id: str, spec: dict[str, Any]) -> dict[str, object]:
    meta = {"id": theme_id, **{k: spec[k] for k in META_KEYS}}
    syntax = {role: {"color": key, **flags} if flags else key for role, (key, flags) in SYNTAX.items()}
    return {"meta": meta, "palette": spec["palette"], "roles": dict(ROLES), "syntax": syntax}


def main() -> None:
    themes = tomllib.loads(SOURCE.read_text(encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    for theme_id, spec in themes.items():
        header = f"# {spec['name']} — generated by tools/themes/make_builtin.py; edit palettes.toml instead.\n"
        (OUT / f"{theme_id}.toml").write_text(header + tomli_w.dumps(theme_document(theme_id, spec)), "utf-8")
    print(f"wrote {len(themes)} themes to {OUT}")


if __name__ == "__main__":
    main()
