"""Help ▸ User Guide / Quick Start / What's New (docs/14 §4.1): the bundled user guide, language reference and
changelog (resources/help, generated by tools/gen_reference.py) as markdown in a themed, non-modal browser.
Links between the pages work; one instance is reused."""

from __future__ import annotations

from pathlib import Path

from PySide6.QtCore import QUrl
from PySide6.QtWidgets import QDialog, QHBoxLayout, QPushButton, QTextBrowser, QVBoxLayout, QWidget

from ...themes.model import Theme
from ..i18n import tr

HELP = Path(__file__).resolve().parents[2] / "resources" / "help"


class GuideBrowser(QDialog):
    def __init__(self, theme: Theme, parent: QWidget | None = None) -> None:
        super().__init__(parent)
        self.setWindowTitle(tr("Structura Help"))
        self.resize(760, 780)
        self.browser = QTextBrowser()
        self.browser.setOpenExternalLinks(True)
        self.browser.setSearchPaths([str(HELP)])
        self.browser.setAccessibleName(tr("Help page"))
        row = QHBoxLayout()
        contents = lambda: self.show_page()  # noqa: E731, PLW0108 - 'clicked' would pass its bool as the page
        for title, action in ((tr("Back"), self.browser.backward), (tr("Contents"), contents)):
            button = QPushButton(title)
            button.clicked.connect(action)
            row.addWidget(button)
        row.addStretch(1)
        layout = QVBoxLayout(self)
        layout.addLayout(row)
        layout.addWidget(self.browser, 1)
        self.set_theme(theme)

    def set_theme(self, theme: Theme) -> None:
        css = (f"code {{ color: {theme['syntax.keyword'][:7]}; }} a {{ color: {theme['ui.accent'][:7]}; }}"
               f" th {{ text-align: left; }} td, th {{ padding: 2px 8px; }}")  # fmt: skip
        self.browser.document().setDefaultStyleSheet(css)

    def show_page(self, name: str = "README.md") -> None:
        page = HELP / name
        self.browser.setSource(QUrl.fromLocalFile(str(page if page.exists() else HELP / "README.md")))
        self.show()
        self.raise_()
        self.activateWindow()
