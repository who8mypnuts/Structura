""" "Autosave script with seed and camera" (docs/15 §5.2, 1.5's getScriptWithSettings): next to a template
export, the script as it was exported — its camera lines replaced by the viewport camera and the seed set."""

from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path

from ...core.scene.camera import Camera
from ...core.scene.camera_script import with_camera

SEED_LINE = re.compile(r"^[ \t]*set[ \t]+seed[ \t]+\d+[^\n]*\n?", re.MULTILINE | re.IGNORECASE)


def autosave_path(exported: Path) -> Path:
    """'scene.pov' → 'scene.es' (1.5 named it after the exported file)."""
    return exported.with_suffix(".es")


def script_with_settings(text: str, camera: Camera, seed: int, exported: Path, v2: bool, now: datetime) -> str:
    """``text`` re-created exactly: a header, the camera, 'set seed' (replacing the script's own), the script."""
    body = with_camera(SEED_LINE.sub("", text), camera, v2)
    header = [
        f"// Autogenerated script for file: {exported}",
        f"// Generated {now:%B %d %Y %H:%M:%S}",
        "",
    ]
    lines = body.split("\n")
    version = 1 if lines and lines[0].lstrip().startswith("#version") else 0
    return "\n".join([*lines[:version], *header, f"set seed {seed}", *lines[version:]])
